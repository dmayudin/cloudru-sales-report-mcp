#!/usr/bin/env python3
"""Run as root on the VM once. Builds /etc/cloudru-sales/secrets.env and the MCP client token from the transferred
bootstrap file, then shreds that file. Non-interactive counterpart of cloudru_mcp.credentials: the Cloud.ru key was
entered by the user in a protected terminal and the passwords were generated by the agent.
Usage: make_secrets.py [--token-days N]   (default 7). Input: /root/bootstrap-secrets.json
  {key_id, key_secret, tenant_id, importer_password, reader_password}"""
import hashlib, json, os, secrets, subprocess, sys, time
from pathlib import Path

days = int(sys.argv[sys.argv.index('--token-days') + 1]) if '--token-days' in sys.argv else 7
src = Path('/root/bootstrap-secrets.json')
d = json.loads(src.read_text())
out = Path('/etc/cloudru-sales/secrets.env'); tok = Path('/etc/cloudru-sales/client-token')
if out.exists() or tok.exists(): raise SystemExit('secrets already exist; refusing to overwrite (use rotate_token.py)')
token = secrets.token_urlsafe(48)
values = {'CLOUDRU_KEY_ID': d['key_id'], 'CLOUDRU_KEY_SECRET': d['key_secret'],
          'CLOUDRU_S3_ACCESS_KEY': d['tenant_id'] + ':' + d['key_id'], 'CLOUDRU_S3_SECRET_KEY': d['key_secret'],
          'CLOUDRU_CH_PASSWORD': d['importer_password'], 'CLOUDRU_BI_CH_PASSWORD': d['reader_password'],
          'CLOUDRU_MCP_TOKEN_SHA256': hashlib.sha256(token.encode()).hexdigest(),
          'CLOUDRU_MCP_TOKEN_EXPIRES': str(int(time.time()) + days * 86400)}
q = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def save(p, text, mode=0o600):
    fd = os.open(p, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
    with os.fdopen(fd, 'w') as f: f.write(text)
save(out, '\n'.join(k + '=' + q(v) for k, v in values.items()) + '\n')
save(tok, token + '\n')
subprocess.run(['chgrp', 'cloudru-sales', str(out)], check=True); os.chmod(out, 0o640)
subprocess.run(['shred', '-u', str(src)], check=True)
print(f'secrets.env (0640 root:cloudru-sales) and client-token (0600 root) written; token valid {days} days; bootstrap file shredded')
